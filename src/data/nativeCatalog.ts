export function getCatalogCategories(): string[] {
  const cats = new Set<string>();
  for (const item of NATIVE_CATALOG) {
    cats.add(item.category);
  }
  return Array.from(cats);
}

export function searchCatalog(query: string, categoryFilter?: string): CatalogItem[] {
  const q = query.trim().toLowerCase();
  return NATIVE_CATALOG.filter(item => {
    if (categoryFilter && categoryFilter !== 'all' && item.category !== categoryFilter) {
      return false;
    }
    if (!q) return true;
    return (
      item.name.toLowerCase().includes(q) ||
      item.category.toLowerCase().includes(q) ||
      item.tags.some(t => t.toLowerCase().includes(q))
    );
  });
}
